-- =====================================================================
-- TratoSeguro EC - Mejoras del core (Flyway V2)
-- Solo agrega columnas y tablas: no borra nada de lo que ya existe en el servidor.
--   1. Stripe Connect: cuenta de cobro del vendedor (modo de prueba)
--   2. Evidencia con archivos (fotos o PDF guardados en la base)
--   3. Calificaciones del vendedor (reputación)
-- =====================================================================

-- ---------- 1. Cuenta de cobro del vendedor en Stripe Connect ----------
-- stripe_cuenta_id: la cuenta conectada (acct_...) donde se transfiere el neto al liberar el pago
-- stripe_cobros_activos: Stripe confirmó que la cuenta ya puede recibir transferencias
ALTER TABLE usuario ADD COLUMN stripe_cuenta_id VARCHAR(255);
ALTER TABLE usuario ADD COLUMN stripe_cobros_activos BOOLEAN NOT NULL DEFAULT FALSE;

-- ---------- 2. Archivos de evidencia ----------
-- Render (plan gratuito) borra el disco en cada despliegue, así que el archivo se guarda en la base.
-- Va en su propia tabla para que listar evidencias no cargue los bytes de cada archivo.
CREATE TABLE archivo_evidencia (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evidencia    BIGINT       NOT NULL,
    nombre          VARCHAR(150) NOT NULL,
    tipo_contenido  VARCHAR(50)  NOT NULL,
    tamano          INTEGER      NOT NULL,
    sha256          VARCHAR(64)  NOT NULL,
    datos           BYTEA        NOT NULL,
    CONSTRAINT uk_archivo_evidencia UNIQUE (id_evidencia),
    CONSTRAINT fk_archivo_evidencia FOREIGN KEY (id_evidencia) REFERENCES evidencia (id),
    CONSTRAINT ck_archivo_tipo CHECK (tipo_contenido IN ('image/jpeg', 'image/png', 'image/webp', 'application/pdf')),
    CONSTRAINT ck_archivo_tamano CHECK (tamano > 0 AND tamano <= 5242880)
);

-- ---------- 3. Calificaciones (el comprador califica al vendedor al cerrar el trato) ----------
CREATE TABLE calificacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaccion  BIGINT       NOT NULL,
    id_comprador    BIGINT       NOT NULL,
    id_vendedor     BIGINT       NOT NULL,
    puntaje         INTEGER      NOT NULL,
    comentario      VARCHAR(300),
    fecha           TIMESTAMP    NOT NULL,
    CONSTRAINT uk_calificacion_transaccion UNIQUE (id_transaccion),
    CONSTRAINT fk_calificacion_transaccion FOREIGN KEY (id_transaccion) REFERENCES transaccion (id),
    CONSTRAINT fk_calificacion_comprador FOREIGN KEY (id_comprador) REFERENCES usuario (id),
    CONSTRAINT fk_calificacion_vendedor FOREIGN KEY (id_vendedor) REFERENCES usuario (id),
    CONSTRAINT ck_calificacion_puntaje CHECK (puntaje BETWEEN 1 AND 5),
    CONSTRAINT ck_calificacion_partes CHECK (id_comprador <> id_vendedor)
);

CREATE INDEX ix_evidencia_disputa ON evidencia (id_disputa);
CREATE INDEX ix_calificacion_vendedor ON calificacion (id_vendedor);
CREATE INDEX ix_movimiento_tipo_referencia ON movimiento (tipo, referencia);
