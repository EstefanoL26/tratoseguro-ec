-- =====================================================================
-- TratoSeguro EC - Esquema completo del core (Flyway V1)
-- Funciona igual en H2 (local y pruebas) y en PostgreSQL (Render).
-- =====================================================================

-- Antes el esquema lo creaba Hibernate. Esta migración lo reemplaza por el del core:
-- se borran las tablas antiguas (solo tenían datos de ejemplo, que DatosIniciales vuelve a cargar).
DROP TABLE IF EXISTS notificacion CASCADE;
DROP TABLE IF EXISTS evidencia CASCADE;
DROP TABLE IF EXISTS disputa CASCADE;
DROP TABLE IF EXISTS historial CASCADE;
DROP TABLE IF EXISTS movimiento CASCADE;
DROP TABLE IF EXISTS envio CASCADE;
DROP TABLE IF EXISTS transaccion CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;
DROP TABLE IF EXISTS ciudad CASCADE;
DROP TABLE IF EXISTS provincia CASCADE;
DROP TABLE IF EXISTS feriado CASCADE;

-- ---------- Catálogos ----------

CREATE TABLE provincia (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(2)  NOT NULL,
    nombre  VARCHAR(60) NOT NULL,
    CONSTRAINT uk_provincia_codigo UNIQUE (codigo)
);

CREATE TABLE ciudad (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(80) NOT NULL,
    id_provincia  BIGINT      NOT NULL,
    CONSTRAINT fk_ciudad_provincia FOREIGN KEY (id_provincia) REFERENCES provincia (id)
);

-- Feriados nacionales: los plazos se cuentan en días hábiles (sin fines de semana ni feriados)
CREATE TABLE feriado (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha   DATE         NOT NULL,
    nombre  VARCHAR(100) NOT NULL,
    CONSTRAINT uk_feriado_fecha UNIQUE (fecha)
);

-- ---------- Usuarios ----------

CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(50)  NOT NULL,
    email      VARCHAR(100) NOT NULL,
    password   VARCHAR(255) NOT NULL,
    nombre     VARCHAR(100) NOT NULL,
    cedula     VARCHAR(10)  NOT NULL,
    rol        VARCHAR(30)  NOT NULL,
    id_ciudad  BIGINT,
    CONSTRAINT uk_usuario_username UNIQUE (username),
    CONSTRAINT uk_usuario_cedula UNIQUE (cedula),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('COMPRADOR', 'VENDEDOR', 'MEDIADOR', 'FINANZAS', 'ADMIN')),
    CONSTRAINT fk_usuario_ciudad FOREIGN KEY (id_ciudad) REFERENCES ciudad (id)
);

-- ---------- Core: el trato y su dinero ----------

CREATE TABLE transaccion (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vendedor            BIGINT        NOT NULL,
    id_comprador           BIGINT        NOT NULL,
    producto               VARCHAR(150)  NOT NULL,
    descripcion            VARCHAR(255),
    monto                  NUMERIC(10,2) NOT NULL,
    dias_entrega           INTEGER       NOT NULL,
    estado                 VARCHAR(30)   NOT NULL,
    fecha                  TIMESTAMP     NOT NULL,
    fecha_pago             TIMESTAMP,
    fecha_limite_envio     DATE,
    fecha_limite_revision  DATE,
    -- Resultado de la liquidación (R + comisión + neto = monto)
    reembolso              NUMERIC(10,2),
    comision               NUMERIC(10,2),
    monto_vendedor         NUMERIC(10,2),
    -- Pago: SIMULADO o STRIPE (modo de prueba)
    metodo_pago            VARCHAR(20),
    stripe_session_id      VARCHAR(255),
    stripe_payment_intent  VARCHAR(255),
    -- Bloqueo optimista: evita liquidar el mismo dinero dos veces
    version                BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT fk_transaccion_vendedor FOREIGN KEY (id_vendedor) REFERENCES usuario (id),
    CONSTRAINT fk_transaccion_comprador FOREIGN KEY (id_comprador) REFERENCES usuario (id),
    CONSTRAINT ck_transaccion_estado CHECK (estado IN ('CREADA', 'PAGADA', 'ENVIADA', 'LIBERADA', 'EN_DISPUTA', 'REEMBOLSADA', 'CANCELADA')),
    CONSTRAINT ck_transaccion_monto CHECK (monto >= 1 AND monto <= 10000),
    CONSTRAINT ck_transaccion_dias CHECK (dias_entrega BETWEEN 1 AND 30),
    CONSTRAINT ck_transaccion_partes CHECK (id_vendedor <> id_comprador)
);

CREATE TABLE envio (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaccion  BIGINT       NOT NULL,
    transportista   VARCHAR(100) NOT NULL,
    guia            VARCHAR(100) NOT NULL,
    fecha           TIMESTAMP    NOT NULL,
    CONSTRAINT uk_envio_transaccion UNIQUE (id_transaccion),
    CONSTRAINT fk_envio_transaccion FOREIGN KEY (id_transaccion) REFERENCES transaccion (id)
);

-- Contabilidad: cada peso retenido, liberado, cobrado como comisión o reembolsado deja un movimiento
CREATE TABLE movimiento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaccion  BIGINT        NOT NULL,
    tipo            VARCHAR(30)   NOT NULL,
    monto           NUMERIC(10,2) NOT NULL,
    fecha           TIMESTAMP     NOT NULL,
    referencia      VARCHAR(255),
    CONSTRAINT fk_movimiento_transaccion FOREIGN KEY (id_transaccion) REFERENCES transaccion (id),
    CONSTRAINT ck_movimiento_tipo CHECK (tipo IN ('RETENCION', 'LIBERACION', 'COMISION', 'REEMBOLSO')),
    CONSTRAINT ck_movimiento_monto CHECK (monto >= 0)
);

-- Expediente del trato: quién cambió el estado, cuándo y por qué (id_usuario vacío = sistema)
CREATE TABLE historial (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaccion  BIGINT       NOT NULL,
    id_usuario      BIGINT,
    estado_ant      VARCHAR(30),
    estado_nuevo    VARCHAR(30)  NOT NULL,
    fecha           TIMESTAMP    NOT NULL,
    motivo          VARCHAR(255),
    CONSTRAINT fk_historial_transaccion FOREIGN KEY (id_transaccion) REFERENCES transaccion (id),
    CONSTRAINT fk_historial_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id)
);

CREATE TABLE disputa (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaccion    BIGINT        NOT NULL,
    id_mediador       BIGINT,
    motivo            VARCHAR(255)  NOT NULL,
    decision          VARCHAR(30),
    reembolso         NUMERIC(10,2),
    via_rapida        BOOLEAN       NOT NULL DEFAULT FALSE,
    justificacion     VARCHAR(500),
    fecha_apertura    TIMESTAMP     NOT NULL,
    fecha_resolucion  TIMESTAMP,
    CONSTRAINT uk_disputa_transaccion UNIQUE (id_transaccion),
    CONSTRAINT fk_disputa_transaccion FOREIGN KEY (id_transaccion) REFERENCES transaccion (id),
    CONSTRAINT fk_disputa_mediador FOREIGN KEY (id_mediador) REFERENCES usuario (id),
    CONSTRAINT ck_disputa_decision CHECK (decision IN ('REEMBOLSO_TOTAL', 'REEMBOLSO_PARCIAL', 'PAGO_AL_VENDEDOR'))
);

CREATE TABLE evidencia (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_disputa   BIGINT       NOT NULL,
    id_usuario   BIGINT       NOT NULL,
    descripcion  VARCHAR(255) NOT NULL,
    archivo      VARCHAR(255),
    fecha        TIMESTAMP    NOT NULL,
    CONSTRAINT fk_evidencia_disputa FOREIGN KEY (id_disputa) REFERENCES disputa (id),
    CONSTRAINT fk_evidencia_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id)
);

-- Notificaciones internas (no se envían correos ni SMS reales)
CREATE TABLE notificacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      BIGINT       NOT NULL,
    id_transaccion  BIGINT,
    mensaje         VARCHAR(255) NOT NULL,
    leida           BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha           TIMESTAMP    NOT NULL,
    CONSTRAINT fk_notificacion_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id),
    CONSTRAINT fk_notificacion_transaccion FOREIGN KEY (id_transaccion) REFERENCES transaccion (id)
);

-- Índices para las consultas más frecuentes
CREATE INDEX ix_transaccion_vendedor ON transaccion (id_vendedor);
CREATE INDEX ix_transaccion_comprador ON transaccion (id_comprador);
CREATE INDEX ix_transaccion_estado ON transaccion (estado);
CREATE INDEX ix_movimiento_transaccion ON movimiento (id_transaccion);
CREATE INDEX ix_historial_transaccion ON historial (id_transaccion);
CREATE INDEX ix_notificacion_usuario ON notificacion (id_usuario, leida);
