-- TratoSeguro EC - Notificaciones push al celular (Flyway V3)
-- Solo agrega una tabla: no cambia ni borra nada de lo que ya existe.
-- Cada fila es un navegador o celular que aceptó recibir avisos de un usuario.
-- =====================================================================

-- endpoint: dirección del servicio de push del navegador (Google, Apple, Mozilla) para ese dispositivo
-- p256dh y auth: claves públicas del navegador para cifrar el aviso (solo ese dispositivo puede leerlo)
CREATE TABLE push_suscripcion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario  BIGINT       NOT NULL,
    endpoint    VARCHAR(500) NOT NULL,
    p256dh      VARCHAR(200) NOT NULL,
    auth        VARCHAR(100) NOT NULL,
    fecha       TIMESTAMP    NOT NULL,
    CONSTRAINT uk_push_endpoint UNIQUE (endpoint),
    CONSTRAINT fk_push_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id)
);

CREATE INDEX ix_push_usuario ON push_suscripcion (id_usuario);
